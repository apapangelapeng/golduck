class Level4(Level):
    GLYPH_WIDTH = 8
    GLYPH_HEIGHT = 14
    GLYPH_SPACING = 2
    SECRET_DIGITS = 16
    SECRET_WIDTH = (
        SECRET_DIGITS * GLYPH_WIDTH + (SECRET_DIGITS - 1) * GLYPH_SPACING
    )
    SECRET_HEIGHT = GLYPH_HEIGHT

    CANVAS_X = -5000
    CANVAS_Y = -5000
    CANVAS_W = 10000
    CANVAS_H = 10000

    SECRET_X = -(SECRET_WIDTH // 2)
    SECRET_Y = -1000 - (SECRET_HEIGHT // 2)

    CONTESTANT_W = 10000
    CONTESTANT_H = 300
    CONTESTANT_X = -(CONTESTANT_W // 2)
    CONTESTANT_Y = -(CONTESTANT_H // 2)

    VIEW_W = 5000
    VIEW_H = 300
    VIEW_X = -(VIEW_W // 2)
    VIEW_Y = 1000 - (VIEW_H // 2)

    MIN_GENERATIONS = 0
    MAX_GENERATIONS = 200000
    MAX_RUNS = 10

    def __init__(self, secret: int):
        super().__init__(secret)
        self._secret_rle: str | None = None

    def get_secret(self) -> tuple[int, int, str]:
        if self._secret_rle is None:
            cells: set[tuple[int, int]] = set()
            for digit_index, digit in enumerate(f"{self.secret:016x}"):
                glyph_x = digit_index * (self.GLYPH_WIDTH + self.GLYPH_SPACING)
                for y, row in enumerate(_FONT_ROWS[digit]):
                    for x, value in enumerate(row):
                        if value == "#":
                            cells.add((glyph_x + x, y))
            pattern = pattern_from_cells(
                cells, self.SECRET_WIDTH, self.SECRET_HEIGHT
            )
            self._secret_rle = encode_rle(pattern)
        return self.SECRET_X, self.SECRET_Y, self._secret_rle

    def get_canvas_rect(self) -> tuple[int, int, int, int]:
        return self.CANVAS_X, self.CANVAS_Y, self.CANVAS_W, self.CANVAS_H

    def get_contestant_rect(self) -> tuple[int, int, int, int]:
        return (
            self.CONTESTANT_X,
            self.CONTESTANT_Y,
            self.CONTESTANT_W,
            self.CONTESTANT_H,
        )

    def get_viewing_rect(self) -> tuple[int, int, int, int]:
        return self.VIEW_X, self.VIEW_Y, self.VIEW_W, self.VIEW_H

    def get_generation_range(self) -> tuple[int, int]:
        return self.MIN_GENERATIONS, self.MAX_GENERATIONS

    def get_max_runs(self) -> int:
        return self.MAX_RUNS
